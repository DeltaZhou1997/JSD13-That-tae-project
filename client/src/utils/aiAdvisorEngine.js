// ฟังก์ชัน RAG Assistant ตอบคำถามผู้ใช้
export function queryThatTaeAI({ question, userElement, cartItems = [], allProducts = [] }) {
  const q = (question || "").trim().toLowerCase();
  const elKey = userElement ? (userElement.replace("ธาตุ", "").trim()) : null;
  const targetElement = elKey && ELEMENT_KNOWLEDGE_BASE[elKey] ? ELEMENT_KNOWLEDGE_BASE[elKey] : null;

  // 1. ถามเรื่องธาตุประจำตัว / เมนูแนะนำตามธาตุ
  if (q.includes("ธาตุของฉัน") || q.includes("กินอะไรดี") || q.includes("อาหารประจำธาตุ") || q.includes("แนะนำอาหาร")) {
    if (targetElement) {
      const matchDishes = allProducts
        .filter(p => p.dominantElement === targetElement.element || (Array.isArray(p.elementSuitability) && p.elementSuitability.includes(targetElement.element)))
        .slice(0, 3)
        .map(p => p.nameTh || p.name);

      return {
        reply: `คุณคือ **${targetElement.name} (ธาตุ${targetElement.element})** 🌿\n\n• **รสชาติปรับสมดุล:** ${targetElement.balanceTastes.join(", ")}\n• **คำแนะนำ:** ${targetElement.seasonalAdvice}\n• **วัตถุดิบชูโรง:** ${targetElement.recommendedFoods.slice(0, 4).join(", ")}\n\n✨ **เมนูที่เหมาะกับคุณ:** ${matchDishes.length > 0 ? matchDishes.join(", ") : "เมนูรส " + targetElement.balanceTastes[0] + " หรือต้มจืดสมุนไพร"}`,
        highlightElement: targetElement.element
      };
    } else {
      return {
        reply: `ยินดีต้อนรับครับ! คุณสามารถ **ทำแบบทดสอบธาตุเจ้าเรือน** เพื่อให้ผมวิเคราะห์และแนะนำอาหารที่เหมาะกับร่างกายของคุณได้อย่างแม่นยำ หรือพิมพ์สอบถามอาการ เช่น "ท้องอืด", "ร้อนใน" ได้ทันทีครับ ✨`,
        highlightElement: null
      };
    }
  }

  // 2. ท้องอืด / ขับลม / ลมในท้อง
  if (q.includes("ท้องอืด") || q.includes("แน่นท้อง") || q.includes("ขับลม") || q.includes("ลม")) {
    const windInfo = ELEMENT_KNOWLEDGE_BASE["ลม"];
    return {
      reply: `🍃 **อาการท้องอืด/แน่นท้อง** เกิดจากธาตุลมแปรปรวน\n\n• **รสชาติบำบัด:** รสเผ็ดร้อนและสุขุมหอม\n• **สมุนไพรแนะนำ:** ขิง ข่า ตะไคร้ กะเพรา พริกไทยดำ\n• **เมนูแนะนำ:** แกงป่า, ต้มข่าไก่, ผัดกะเพรา หรือจิบน้ำขิงอุ่นๆ เลี่ยงอาหารย่อยยากและน้ำเย็นจัดครับ`,
      highlightElement: "ลม"
    };
  }

  // 3. ร้อนใน / ขี้ร้อน / ดับร้อน / เป็นไข้
  if (q.includes("ร้อนใน") || q.includes("ขี้ร้อน") || q.includes("ดับร้อน") || q.includes("ไข้") || q.includes("เจ็บคอ")) {
    const fireInfo = ELEMENT_KNOWLEDGE_BASE["ไฟ"];
    return {
      reply: `🔥 **อาการร้อนใน/ตัวร้อน** เกิดจากเตโชธาตุ (ธาตุไฟ) กำเริบ\n\n• **รสชาติบำบัด:** รสขม รสเย็น รสจืด\n• **สมุนไพรแนะนำ:** บัวบก ฟ้าทะลายโจร มะระ เก๊กฮวย รางจืด\n• **เมนูแนะนำ:** ต้มจืดมะระยัดไส้, ต้มจืดตำลึงหมูสับ, แกงจืดฟัก เลี่ยงของทอด ของมัน แอลกอฮอล์ และของรสเผ็ดจัดครับ`,
      highlightElement: "ไฟ"
    };
  }

  // 4. เสมหะ / หวัด / ภูมิแพ้ / คอแห้ง
  if (q.includes("เสมหะ") || q.includes("หวัด") || q.includes("ไอ") || q.includes("เจ็บคอ") || q.includes("น้ำ")) {
    return {
      reply: `💧 **อาการเสมหะเยอะ/ระคายคอ** สัมพันธ์กับอาโปธาตุ (ธาตุน้ำ)\n\n• **รสชาติบำบัด:** รสเปรี้ยว และรสขม\n• **สมุนไพรแนะนำ:** มะขามป้อม มะนาว ขิง ตะไคร้\n• **เมนูแนะนำ:** ต้มยำน้ำใสสมุนไพร, แกงส้ม, ต้มส้มปลา จะช่วยฟอกเสมหะและทำให้ทางเดินหายใจโล่งสบายขึ้นครับ`,
      highlightElement: "น้ำ"
    };
  }

  // 5. วิเคราะห์เมนูในตะกร้าปัจจุบัน
  if (q.includes("ตะกร้า") || q.includes("ในตะกร้า") || q.includes("สั่งอะไร") || q.includes("เมนูของฉัน")) {
    if (cartItems.length === 0) {
      return {
        reply: `ตอนนี้ตะกร้าของคุณยังว่างอยู่ครับ 🛒\nลองเลือกดูเมนูประจำภาค หรือให้ผมช่วยแนะนำเมนูที่ตรงกับธาตุ ${userElement || "เจ้าเรือนของคุณ"} ได้เลยนะครับ!`,
        highlightElement: null
      };
    }
    const itemNames = cartItems.map(i => i.nameTh || i.name).join(", ");
    return {
      reply: `🛒 **เมนูในตะกร้าของคุณ (${cartItems.length} รายการ):**\n${itemNames}\n\n💡 **คำแนะนำ:** หากต้องการให้มื้ออาหารสมดุลครบ 4 ธาตุ แนะนำให้ทานคู่กับผักเคียงสด หรือเลือกเมนูที่มีทั้งรสเผ็ดร้อน (ลม) และรสจืดเย็น (ไฟ) ผสมผสานกันครับ`,
      highlightElement: userElement ? userElement.replace("ธาตุ", "") : null
    };
  }

  // 6. ถามเรื่องรสชาติ / ทฤษฎีรสยา 9 รส
  if (q.includes("รส") || q.includes("รสชาติ")) {
    return {
      reply: `🌿 **คัมภีร์รสยา 9 รสตามศาสตร์การแพทย์แผนไทย:**\n\n• **รสฝาด/หวาน/มัน/เค็ม:** เสริมสร้างและบำรุง **ธาตุดิน**\n• **รสเปรี้ยว/ขม:** กัดเสมหะ ฟอกโลหิต ปรับสมดุล **ธาตุน้ำ**\n• **รสเผ็ดร้อน/หอมเย็น:** ขับลม แก้จุกเสียด บำรุง **ธาตุลม**\n• **รสขม/เย็น/จืด:** ถอนพิษร้อน ดับพิษไข้ ลดความร้อน **ธาตุไฟ**`,
      highlightElement: null
    };
  }

  // คำตอบทั่วไป (General RAG Fallback)
  const defaultInfo = targetElement 
    ? `คุณมีธาตุประจำตัวคือ **ธาตุ${targetElement.element}** เหมาะกับอาหาร${targetElement.balanceTastes.join(", ")} เช่น ${targetElement.recommendedFoods.slice(0, 3).join(", ")}`
    : `คุณสามารถทดสอบธาตุเจ้าเรือนเพื่อรับคำแนะนำเฉพาะบุคคลได้`;

  return {
    reply: `สวัสดีครับ! ผมคือ **That-Tae RAG AI** ผู้ช่วยให้คำปรึกษาโภชนาการตามธาตุเจ้าเรือนและการแพทย์แผนไทย 🌿\n\n${defaultInfo}\n\nคุณสามารถคลิกเลือกคำถามด้านล่าง หรือพิมพ์ถามอาการ เช่น *ท้องอืด*, *ร้อนใน*, *เมนูบำรุงสุขภาพ* ได้ตลอดเวลาครับ!`,
    highlightElement: targetElement ? targetElement.element : null
  };
}
